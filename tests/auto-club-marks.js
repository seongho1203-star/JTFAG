// node tests/auto-club-marks.js — 가상 검색·공식 페이지·AI 응답. 실제 유료 요청·DB 쓰기·배포 없음.
const fs=require('node:fs');
const path=require('node:path');
const assert=require('node:assert/strict');
const {createHash}=require('node:crypto');
const {clubKey,registeredClubs,publicAddress,publicUrl,publicFetch,candidatesFromHtml,imageType,rasterImage,discoverSite,discoverApp,collectCandidates,confirmLogo,update}=require('../scripts/update-club-marks');
const png=fs.readFileSync(path.join(__dirname,'../assets/club-marks/v1/happiness.png'));
const clone=value=>JSON.parse(JSON.stringify(value));
async function main(){
    assert.equal(clubKey('JNJ골프리조트 (정-남)'),'jnj');
    assert.equal(clubKey('골프존카운티 무등산CC'),'무등산');
    const payload={roundCourses:{1:'신규CC',2:'기존CC'},courses:['신규 CC'],trips:[{days:[{course:'예정CC'},{course:'미방문CC',golf:'no'}]}]};
    const snapshot=JSON.stringify(payload);
    assert.deepEqual(registeredClubs(payload,{1:{course:'어등-송정'},2:{course:'덮어쓴이름CC'},3:{course:'추가CC'}}).map(c=>c.key),['신규','기존','추가','예정']);
    assert.equal(JSON.stringify(payload),snapshot);
    const abroad=registeredClubs({trips:[{kind:'japan',days:[{course:'후쿠오카 파인 GC',gora:{ja:'福岡パインゴルフ倶楽部'}},{course:'오사카 컨트리클럽'}]},{kind:'domestic',days:[{course:'국내CC'}]}],passportPast:[{name:'가고시마 CC',country:'JP'}]},{});
    assert.deepEqual(abroad.map(c=>[c.key,c.country||'',c.alt||'']),[['가고시마','일본',''],['후쿠오카파인','일본','福岡パインゴルフ倶楽部'],['오사카','일본',''],['국내','','']]);
    assert.equal(registeredClubs({courses:['__proto__','constructor','<script>CC']},{}).length,0);
    for(const ip of ['127.0.0.1','10.0.0.1','169.254.169.254','172.16.0.1','192.168.0.1','::1','fd00::1'])assert.equal(publicAddress(ip),false,ip);
    assert.equal(publicAddress('1.1.1.1'),true);assert.equal(publicAddress('192.0.78.1'),true);
    const lookup=async()=>[{address:'1.1.1.1'}];
    for(const url of ['file:///etc/passwd','http://localhost/path','https://127.0.0.1/','https://user:pass@official.example/'])await assert.rejects(publicUrl(url,lookup));
    await assert.rejects(publicUrl('https://official.example',async()=>[{address:'10.0.0.1'}]));
    let calls=0;
    await assert.rejects(publicFetch('https://official.example/',{lookup,fetcher:async()=>{calls++;return new Response('',{status:302,headers:{location:'http://127.0.0.1/'}});}}));
    assert.equal(calls,1,'내부 주소로 이동하는 응답을 따라가지 않음');
    const html='<title>신규CC 공식 홈페이지</title><img src="/logo.png" alt="신규 로고"><img src="/course-photo.jpg"><img src="/favicon.png" alt="logo"><img data-src="/logo.png">';
    const candidates=candidatesFromHtml(html,'https://official.example/');
    assert.deepEqual(candidates.map(x=>x.url),['https://official.example/logo.png']);
    assert.equal(imageType(Buffer.from('<html>error</html>')),null);
    const svg=Buffer.from('<svg xmlns="http://www.w3.org/2000/svg" width="100" height="60"><path fill="#246842" d="M0 0H100V60H0Z"/></svg>');
    const rendered=rasterImage(svg);
    assert.ok(rendered && rendered.ext==='png','안전한 SVG를 네트워크 없이 PNG로 렌더링');
    assert.equal(rasterImage(Buffer.from('<svg><image href="file:///etc/passwd"/></svg>')),null);
    assert.equal(rasterImage(Buffer.from('<svg><script>alert(1)</script></svg>')),null);
    const siteReply={content:[{type:'web_search_tool_result',content:[{type:'web_search_result',url:'https://official.example/'}]},{type:'text',text:'{"site_url":"https://official.example/"}'}]};
    let request;
    assert.equal(await discoverSite({name:'신규CC'},async body=>{request=body;return siteReply;}),'https://official.example/');
    assert.equal(request.tools[0].max_uses,2);
    const invented=clone(siteReply);invented.content[1].text='{"site_url":"https://invented.example/"}';
    assert.equal(await discoverSite({name:'신규CC'},async()=>invented),null,'검색에 없는 주소 거부');
    const referenced={content:[{type:'web_search_tool_result',content:[{type:'web_search_result',url:'https://tour.example/club'}]},{type:'text',text:'{"site_url":"https://club.example/","evidence_url":"https://tour.example/club"}'}]};
    assert.equal(await discoverSite({name:'신규CC'},async()=>referenced,async()=>({url:'https://tour.example/club',type:'text/html',bytes:Buffer.from('<a href="https://club.example/">홈페이지</a>')})),'https://club.example/');
    assert.equal(await discoverSite({name:'신규CC'},async()=>referenced,async()=>({url:'https://tour.example/club',type:'text/html',bytes:Buffer.from('<a href="https://other.example/">다른 홈페이지</a>')})),null,'검색 출처의 실제 링크가 다르면 거부');
    const appReply={content:[{type:'web_search_tool_result',content:[{type:'web_search_result',url:'https://play.google.com/store/apps/details?id=kr.example.club'}]},{type:'text',text:'{"app_url":"https://play.google.com/store/apps/details?id=kr.example.club"}'}]};
    assert.match(await discoverApp({name:'신규CC'},async()=>appReply),/id=kr.example.club&hl=ko/);
    const found=await collectCandidates('https://official.example/',async url=>({url,type:url.endsWith('.png')?'image/png':'text/html;charset=utf-8',bytes:url.endsWith('.png')?png:Buffer.from(html)}));
    assert.equal(found.images.length,1);
    const appFound=await collectCandidates('https://play.google.com/store/apps/details?id=kr.example.club',async url=>({url,type:url.endsWith('.png')?'image/png':'text/html;charset=utf-8',bytes:url.endsWith('.png')?png:Buffer.from('<title>신규CC 예약</title><meta property="og:image" content="https://images.example/club.png"><img src="/google-logo.png">')}));
    assert.equal(appFound.images.length,1);
    assert.equal(appFound.images[0].source_url,'https://images.example/club.png','앱 대표 아이콘을 플랫폼 로고와 구분');
    const approved={content:[{type:'tool_use',name:'select_logo',input:{index:0,confirmed:true,background:'#ffffff',ink:'#246842'}}]};
    assert.ok(await confirmLogo({name:'신규CC'},found,async()=>approved));
    const bright=clone(approved);bright.content[0].input.ink='#FFFFFF';
    assert.notEqual((await confirmLogo({name:'신규CC'},found,async()=>bright)).ink,'#FFFFFF','흰 화면에서 원형 테두리가 보이는 색으로 조정');
    const rejected=clone(approved);rejected.content[0].input.confirmed=false;
    assert.equal(await confirmLogo({name:'신규CC'},found,async()=>rejected),null);
    const known={기존:{file:'manual.png'}},catalog={version:1,marks:{}},state={},writes=[];
    let searches=0;
    const options={now:100000,discover:async()=>{searches++;return 'https://official.example/';},fallback:async()=>null,collect:async()=>found,confirm:async()=>({...found.images[0],ext:'png',background:'#ffffff',ink:'#246842'}),saveImage:async(file,bytes)=>writes.push({file,bytes})};
    const clubs=[{key:'기존',name:'기존CC'},{key:'신규',name:'신규CC'}];
    assert.deepEqual(await update(clubs,known,catalog,state,options),{added:['신규CC'],checked:1});
    assert.equal(writes[0].file,'auto-'+createHash('sha256').update(png).digest('hex')+'.png');
    assert.ok(writes[0].bytes.equals(png),'확인된 래스터 마크는 원본 그대로 저장');
    assert.equal(catalog.marks['신규'].source_url,'https://official.example/logo.png');
    await update(clubs,known,catalog,state,options);assert.equal(searches,1,'기존·이미 수집한 골프장은 AI 재조회 없음');
    const retryState={},retryCatalog={version:1,marks:{}};
    const noLogo={...options,confirm:async()=>null};
    await update([{key:'대기',name:'대기CC'}],known,retryCatalog,retryState,noLogo);
    assert.equal(Object.keys(retryCatalog.marks).length,0);
    assert.ok(retryState['대기'].nextTry>options.now);
    assert.equal((await update([{key:'대기',name:'대기CC'}],known,retryCatalog,retryState,noLogo)).checked,0,'재확인 대기 기간에는 유료 재시도 없음');
    const capped=await update(['a','b','c'].map(key=>({key,name:key+'CC'})),{}, {version:1,marks:{}},{},noLogo);
    assert.equal(capped.checked,2,'한 번에 최대 두 골프장만 확인');
    const fallbackCatalog={version:1,marks:{}};
    const appFallback=await update([{key:'앱골프장',name:'앱골프장CC'}],{},fallbackCatalog,{}, {...options,discover:async()=>null,fallback:async()=>'https://play.google.com/store/apps/details?id=kr.example.club'});
    assert.equal(appFallback.added.length,1,'홈페이지에서 못 찾으면 공식 예약 앱 아이콘 확인');
    console.log('PASS: 등록 골프장·별칭·예정 일정 수집, 기존 마크 재사용·입력값 불변');
    console.log('PASS: 검색 근거·공식 HTML 후보·이미지 승인·불확실 시 미등록, 공개 URL·리다이렉트·SVG 검증');
    console.log('PASS: 원본/안전한 PNG·내용 해시 파일 저장, 중복 과금 방지·실패 재확인·실행당 상한');
}
main().catch(err=>{console.error(err);process.exitCode=1;});
